def main() -> None:
    with open(KB, encoding="utf-8") as f:
        data = json.load(f)
    by_cat = {e["category"]: e for e in data["entries"]}
    added = updated = 0
    for e in NEW:
        # 幂等 ①：完全重复的条目不写入（按 category 判重）
        if e["category"] in by_cat:
            old = by_cat[e["category"]]
            # 幂等 ②：条目已存在但 keywords 被补过（第三轮给 K71 加了整句搭配），
            # 用「并集」而不是「覆盖」——手工在知识库里加过的口语说法不能被脚本冲掉。
            merged = list(old.get("keywords", []))
            extra = [k for k in e.get("keywords", []) if k not in merged]
            if extra:
                old["keywords"] = merged + extra
                updated += 1
                print(f"[更新] {e['category']} +{len(extra)} 个关键词")
            else:
                print(f"[跳过] {e['category']} 已存在")
            continue
        data["entries"].append(e)
        by_cat[e["category"]] = e
        added += 1
    data["version"] = "1.3"
    data["updated"] = "2026-10-18"
    with open(KB, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"新增 {added} 条、更新 {updated} 条，现有 {len(data['entries'])} 条")


if __name__ == "__main__":
    main()
