import { describe, expect, it } from "vitest";
import { canonDept, matchDept } from "@/lib/dept";

/**
 * 科室归一化。
 *
 * 这段逻辑守着一条用户可见的链路：报告页「建议科室：神经内科」→ 点
 * 「按科室找医院」→ 医院页下拉框与医院排序。它有两种失败方式，都要钉住：
 *   A. 匹配不上（下拉框空白 / 回落错误科室）——用户看到的是「不是我要的科」
 *   B. 匹配错了（把 A 科映射成 B 科）——更难发现，因为界面上看起来完全正常
 */

const OPTS = [
  "眼科", "心血管内科", "神经内科", "神经外科", "内分泌科", "骨科",
  "呼吸内科", "消化内科", "普外科", "妇产科", "儿科", "口腔科",
  "中医科", "肿瘤科", "精神心理科", "皮肤科", "全科",
] as const;

describe("canonDept 简称补全与多科室取首", () => {
  it.each([
    ["心内科", "心血管内科"],
    ["神内", "神经内科"],
    ["消化", "消化内科"],
    ["内分泌", "内分泌科"],
    ["全科医疗", "全科"],
    ["全科医学", "全科"],
    ["神经内科", "神经内科"],
    ["消化内科 / 普外科", "消化内科"],
    ["消化内科／普外科", "消化内科"],
    ["  眼科  ", "眼科"],
    ["", ""],
  ])("%s → %s", (input, want) => {
    expect(canonDept(input)).toBe(want);
  });

  it("全角斜杠也要能切开（模型输出常见全角）", () => {
    expect(canonDept("心血管内科／内分泌科")).toBe("心血管内科");
  });
});

describe("matchDept 映射到下拉选项", () => {
  it.each([
    // 完全命中
    ["神经内科", "神经内科"],
    ["眼科", "眼科"],
    ["全科", "全科"],
    // 简称补全后命中
    ["心内科", "心血管内科"],
    ["神内", "神经内科"],
    ["神外", "神经外科"],
    ["呼吸", "呼吸内科"],
    // 多科室取首个
    ["消化内科 / 普外科", "消化内科"],
    // 选项包含目标（较长的官方名 → 较短的选项名）
    ["全科医疗科", "全科"],
    ["全科医学科", "全科"],
    // 目标包含选项（分诊写得更具体时的反向兜底）
    ["心血管内科门诊", "心血管内科"],
    ["儿童呼吸科", "呼吸内科"],
  ])("%s → %s", (input, want) => {
    expect(matchDept(input, OPTS)).toBe(want);
  });

  it("找不到对应选项时保留原值，绝不回落到眼科", () => {
    // 这是最重要的一条：回落到「眼科」会让用户以为系统推荐了眼科，
    // 而实际上他查的是血液问题。原样返回至少是诚实的。
    expect(matchDept("血液科", OPTS)).toBe("血液科");
    expect(matchDept("风湿免疫科", OPTS)).toBe("风湿免疫科");
  });

  it("空输入返回空串，让调用方保持原状", () => {
    expect(matchDept("", OPTS)).toBe("");
    expect(matchDept("   ", OPTS)).toBe("");
  });

  it("不会因为去「科」字而误匹配到不相干的科室", () => {
    // 早期版本用「互相包含」匹配，「皮肤」会撞上「皮肤科」这类正常；
    // 但要保证不会出现「内科」这种裸词把第一个带「内科」的选项全吃掉。
    expect(matchDept("皮肤科", OPTS)).toBe("皮肤科");
    expect(matchDept("妇产科", OPTS)).toBe("妇产科");
    expect(matchDept("儿科", OPTS)).toBe("儿科");
  });

  it("多个候选时按重叠长度择优，而不是按选项顺序", () => {
    // 「儿童呼吸科」被「儿科」(2 字) 和「呼吸内科」(3 字) 同时包含。
    // 按选项顺序会先撞上「儿科」→ 呼吸问题被分去儿科，是真错。
    expect(matchDept("儿童呼吸科", OPTS)).toBe("呼吸内科");
    expect(matchDept("小儿消化科", OPTS)).toBe("消化内科");
    expect(matchDept("老年心血管科", OPTS)).toBe("心血管内科");
  });

  it("只重叠一个字不算匹配（否则任何带「科」的名字都会乱撞）", () => {
    // 「疼痛科」与所有选项最多只共用「科」字，必须原样返回而不是
    // 因为 overlap>=1 被塞进某个内科。
    expect(matchDept("疼痛科", OPTS)).toBe("疼痛科");
    expect(matchDept("康复医学科", OPTS)).toBe("康复医学科");
  });
});
